type CorePhraseLocale = keyof typeof corePhraseMessages;
export type MessageKey = keyof typeof corePhraseMessages.ko;
export type CorePhraseMessageKey = MessageKey;

/** CorePhrase용 KO/VI 문구를 반환한다. 그 밖의 기존 UI locale은 KO로 대체한다. */
export function t(
  key: MessageKey,
  locale: UiLocale = getUiLocale(),
  values: Record<string, string | number> = {},
): string {
  const currentLocale: CorePhraseLocale = locale === 'vi' ? 'vi' : 'ko';
  const template: string = corePhraseMessages[currentLocale][key];
  return template.replace(/{{(\w+)}}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}
